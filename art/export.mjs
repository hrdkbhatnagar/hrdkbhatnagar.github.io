// Bake the riso art in art/riso.html to public/images/riso/<asset>-<size>@<dpr>x.png.
//
//   node art/export.mjs
//
// Needs a local clone of riso-windowseat with its tools installed (cd tools && npm install
// && npm run setup); set RISO_TOOLS if it isn't at ./riso-windowseat/tools.
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const tools = path.resolve(root, process.env.RISO_TOOLS || 'riso-windowseat/tools');
const { launch, openFilm } = await import(url.pathToFileURL(path.join(tools, 'lib/browser.mjs')).href);

// 1. The hand-drawn marks' geometry, read out of src/marks/*.svg
const MARKS = ['neuron-rule', 'neuron-rule-short', 'rule', 'arrow'];
const geometry = {};
for (const name of MARKS) {
  const svg = fs.readFileSync(path.join(root, 'src/marks', name + '.svg'), 'utf8')
    .replace(/<defs>[\s\S]*?<\/defs>/g, '')
    .replace(/<mask[\s\S]*?<\/mask>/g, '');
  const attr = (tag, k) => (tag.match(new RegExp(`\\s${k}="([^"]*)"`)) || [])[1];
  const g = { fills: [], strokes: [], circles: [] };
  for (const tag of svg.match(/<path\b[^>]*>/g) || []) {
    const d = attr(tag, 'd'), width = attr(tag, 'stroke-width');
    if (attr(tag, 'fill') === 'none') g.strokes.push({ d, width: Number(width || 1) });
    else g.fills.push(d);
  }
  for (const tag of svg.match(/<circle\b[^>]*>/g) || []) g.circles.push(['cx', 'cy', 'r'].map((k) => Number(attr(tag, k))));
  geometry[name] = g;
}
fs.writeFileSync(path.join(root, 'art/geometry.js'),
  '// Generated by art/export.mjs from src/marks/*.svg. Do not edit.\nwindow.RISO_GEOMETRY = ' + JSON.stringify(geometry) + ';\n');
console.log('wrote art/geometry.js');

// 2. Every asset, at every size and device pixel ratio
const outDir = path.join(root, 'public/images/riso');
fs.mkdirSync(outDir, { recursive: true });
const browser = await launch(process.env.RISO_ENGINE || 'firefox');
try {
  const { page, errors } = await openFilm(browser, path.join(root, 'art/riso.html'));
  const assets = await page.evaluate(() => window.__riso.assets);
  for (const [id, sizes] of Object.entries(assets)) {
    for (const size of Object.keys(sizes)) {
      for (const dpr of [1, 2, 3]) {
        const data = await page.evaluate(([i, s, d]) => window.__riso.bake(i, s, d), [id, size, dpr]);
        const again = await page.evaluate(([i, s, d]) => window.__riso.bake(i, s, d), [id, size, dpr]);
        if (data !== again) throw Error(`${id} ${size} @${dpr}x is not repeatable`);
        const file = path.join(outDir, `${id}-${size}@${dpr}x.png`);
        fs.writeFileSync(file, Buffer.from(data.split(',')[1], 'base64'));
      }
      console.log(`baked ${id} (${size}: ${sizes[size].join('×')} css px) @1x 2x 3x`);
    }
  }
  if (errors.length) throw Error(errors.join('\n'));
  // the sizes, for src/components/Riso.astro
  fs.writeFileSync(path.join(root, 'src/data/riso.json'), JSON.stringify(assets, null, 2) + '\n');
  console.log('wrote src/data/riso.json');
} finally {
  await browser.close();
}
